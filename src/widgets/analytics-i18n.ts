export const tr = makeT<K>({ en, fr, es, pt });

/** "3 wins", "1 loss": a streak of trades. */
export function tradeRun(kind: "win" | "loss", n: number): string {
	if (kind === "win") return n === 1 ? tr("oneWin") : tr("winsN", { n });
	return n === 1 ? tr("oneLoss") : tr("lossesN", { n });
}

/** "1 day traded", "3 days traded". */
export function daysTraded(n: number): string {
	return n === 1 ? tr("oneDayTraded") : tr("daysTradedN", { n });
}

/** "1 winner", "3 losers". */
export function outcomeCount(kind: "win" | "loss", n: number): string {
	if (kind === "win") return n === 1 ? tr("oneWinner") : tr("winnersN", { n });
	return n === 1 ? tr("oneLoser") : tr("losersN", { n });
}

/** "3 winning days", "1 losing day": a streak of days. */
export function dayRun(kind: "win" | "loss", n: number): string {
	if (kind === "win") return n === 1 ? tr("oneWinDay") : tr("winDaysN", { n });
	return n === 1 ? tr("oneLossDay") : tr("lossDaysN", { n });
}
