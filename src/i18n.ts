const DICTS: Record<string, Partial<Record<Key, string>>> = { fr, es, pt };

/** Language of Obsidian reduced to the four of Tradoshi ("pt-BR" becomes "pt"). */
export function language(): "en" | "fr" | "es" | "pt" {
	const lang = (getLanguage() || "en").toLowerCase().slice(0, 2);
	return lang === "fr" || lang === "es" || lang === "pt" ? lang : "en";
}

export function t(key: Key, vars: Record<string, string | number> = {}): string {
	const text = DICTS[language()]?.[key] ?? en[key];
	return text.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? ""));
}

// Mistake tags of the sample journal, in the language of the interface.
const SAMPLE_TAGS: Record<string, Record<string, string>> = {
	fr: { "Outside killzone": "Hors killzone", Oversized: "Sur-dimensionné", Impulsive: "Impulsif", "Early exit": "Sortie anticipée" },
	es: { "Outside killzone": "Fuera de killzone", Oversized: "Sobredimensionado", Impulsive: "Impulsivo", "Early exit": "Salida anticipada" },
	pt: { "Outside killzone": "Fora da killzone", Oversized: "Superdimensionado", Impulsive: "Impulsivo", "Early exit": "Saída antecipada" },
};

export function sampleTag(tag: string): string {
	return SAMPLE_TAGS[language()]?.[tag] ?? tag;
}

/** "1 trade", "3 trades". */
export function tradesLabel(n: number): string {
	return n === 1 ? t("tradeCount") : t("tradesCount", { n });
}

/** Translates the emotion keys of the sample journal, and shows real ones as written. */
export function emotionLabel(emotion: string): string {
	return emotion in en ? t(emotion as Key) : emotion.charAt(0).toUpperCase() + emotion.slice(1);
}

/** Locale for numbers and dates. */
export function locale(): string {
	return { en: "en-US", fr: "fr-FR", es: "es-ES", pt: "pt-BR" }[language()];
}
