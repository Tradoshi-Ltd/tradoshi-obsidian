export function statusLabel(s: SetupStatus): string {
	return s === "paused" ? st("statusPaused") : s === "testing" ? st("statusTesting") : st("statusActive");
}

const HEALTH: Record<HealthIssue, SetupKey> = {
	noSheet: "hNoSheet",
	noDescription: "hNoDescription",
	noPlaybook: "hNoPlaybook",
	noRules: "hNoRules",
	noExamples: "hNoExamples",
	fewTrades: "hFewTrades",
	pausedTraded: "hPausedTraded",
};

export function healthLabel(h: HealthIssue): string {
	return st(HEALTH[h]);
}

export function edgeLabel(level: EdgeLevel, positive: boolean): string {
	if (level === "early") return st("eEarly");
	if (level === "noise") return st("eNoise");
	if (level === "emerging") return positive ? st("eEmergingUp") : st("eEmergingDown");
	return positive ? st("eSolidUp") : st("eSolidDown");
}

export function sortLabel(s: SetupSort): string {
	return s === "net" ? t("net") : s === "expectancy" ? t("expectancy") : s === "trades" ? t("trades") : s === "winRate" ? t("winRate") : s === "profitFactor" ? t("profitFactor") : t("avgR");
}
